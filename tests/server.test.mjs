import test from 'node:test';
import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { gunzipSync } from 'node:zlib';
import http from 'node:http';
import { defaults, serviceDefaults } from '../public/model.js';

test('local API saves, reopens, detects conflicts, previews and exports', async t => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'picreator-api-'));
  process.env.PICREATOR_DATA = path.join(temp, 'data'); process.env.PICREATOR_EXPORTS = path.join(temp, 'exports');
  const { server } = await import('../server.mjs');
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve)); t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const call = (route, method = 'GET', data) => fetch(base + route, { method, headers: data ? { 'Content-Type': 'application/json' } : {}, body: data ? JSON.stringify(data) : undefined });
  const html = await call('/'); assert.equal(html.status, 200); assert.match(await html.text(), /Pi Creator/);
  const p = defaults();
  const created = await (await call('/api/projects', 'POST', { config: p })).json(); assert.ok(created.id); assert.equal(created.revision, 1);
  const route = '/api/projects/' + created.id;
  assert.deepEqual((await (await call(route)).json()).config, p);
  assert.equal((await call(route + '/export', 'POST', { revision: 1 })).status, 422);
  p.ssh.enabled = false; p.project.name = 'Integration test';
  const saved = await (await call(route, 'PUT', { config: p, revision: 1 })).json(); assert.equal(saved.revision, 2);
  assert.equal((await call(route, 'PUT', { config: p, revision: 1 })).status, 409);
  const simultaneous = await Promise.all([call(route, 'PUT', { config: p, revision: 2 }), call(route, 'PUT', { config: p, revision: 2 })]);
  assert.deepEqual(simultaneous.map(x => x.status).sort(), [200, 409]);
  const preview = await (await call('/api/preview', 'POST', { config: p })).json(); assert.ok(preview.files['config.yaml']);
  const exported = await (await call(route + '/export', 'POST', { revision: 3 })).json();
  assert.deepEqual(JSON.parse(await fs.readFile(path.join(exported.folder, 'project.json'), 'utf8')), p);
  const modified = structuredClone(p); modified.project.name = 'Changed after export';
  assert.equal((await call(route, 'PUT', { config: modified, revision: 3 })).status, 200);
  const download = await call(exported.download); assert.equal(download.status, 200); assert.ok(gunzipSync(Buffer.from(await download.arrayBuffer())).includes(Buffer.from('config.yaml')));
  const snapshot = gunzipSync(Buffer.from(await (await call(exported.download)).arrayBuffer())).toString();
  assert.ok(snapshot.includes('Integration test')); assert.ok(!snapshot.includes('Changed after export'));
  assert.equal((await call('/api/projects', 'POST', { config: { ...p, users: [null] } })).status, 400);
  assert.equal((await call('/api/projects', 'POST', { config: { ...p, system: {} } })).status, 400);
  assert.equal((await fetch(base + '/api/projects', { headers: { Origin: 'https://evil.example' } })).status, 403);
  const badHost = await new Promise((resolve, reject) => { http.get(base + '/api/projects', { headers: { Host: 'evil.example' } }, r => { r.resume(); resolve(r.statusCode); }).on('error', reject); });
  assert.equal(badHost, 403);
  assert.equal((await fetch(base + '/api/projects', { method: 'POST', body: '{}' })).status, 415);
  assert.equal((await call('/server.mjs')).status, 404);
  assert.equal((await (await call('/api/projects')).json()).length, 1);
  const legacy = defaults(); delete legacy.serviceAccounts; delete legacy.services;
  const imported = await (await call('/api/projects', 'POST', { config: legacy })).json();
  assert.deepEqual(imported.config.serviceAccounts, []); assert.deepEqual(imported.config.services, []);
  imported.config.ssh.enabled = false;
  imported.config.serviceAccounts.push({ name: 'worker', groups: 'i2c' });
  imported.config.services.push({ ...serviceDefaults(), account: 'worker' });
  const updated = await (await call('/api/projects/' + imported.id, 'PUT', { config: imported.config, revision: 1 })).json();
  const reopened = await (await call('/api/projects/' + imported.id)).json();
  assert.deepEqual(reopened.config.serviceAccounts, imported.config.serviceAccounts);
  assert.deepEqual(reopened.config.services, imported.config.services);
  const serviceExport = await (await call('/api/projects/' + imported.id + '/export', 'POST', { revision: updated.revision })).json();
  assert.match(await fs.readFile(path.join(serviceExport.folder, 'services/myapp.service'), 'utf8'), /User=worker/);
  reopened.config.updates.strategy = 'ab'; reopened.config.sizing.fillData = true;
  const abSave = await (await call('/api/projects/' + imported.id, 'PUT', { config: reopened.config, revision: reopened.revision })).json();
  const abExport = await (await call('/api/projects/' + imported.id + '/export', 'POST', { revision: abSave.revision })).json();
  assert.match(await fs.readFile(path.join(abExport.folder, 'config.yaml'), 'utf8'), /layer: "image-rota"/);
  assert.match(await fs.readFile(path.join(abExport.folder, 'STORAGE.md'), 'utf8'), /32 decimal GB/);
});

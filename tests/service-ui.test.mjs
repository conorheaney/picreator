import test from 'node:test';
import assert from 'node:assert/strict';

test('guided UI adds accounts and services, propagates renames and blocks deleting referenced accounts', async () => {
  const originalTimeout = globalThis.setTimeout;
  const timers = [];
  globalThis.setTimeout = (...args) => { const timer = originalTimeout(...args); timers.push(timer); return timer; };
  const nodes = new Map(), events = new Map();
  const node = key => { if (!nodes.has(key)) nodes.set(key, { innerHTML: '', textContent: '', addEventListener() {}, showModal() { this.open = true; }, close() { this.open = false; } }); return nodes.get(key); };
  globalThis.document = { querySelector: node, addEventListener: (name, fn) => events.set(name, fn) };
  globalThis.window = { addEventListener() {}, scrollTo() {} };
  globalThis.localStorage = { getItem: () => null, setItem() {} };
  const originalFetch = globalThis.fetch;
  try {
    await import('../public/app.js');
    const click = async dataset => { events.get('click')({ target: { closest: () => ({ dataset }) } }); await Promise.resolve(); await Promise.resolve(); };
    const input = (path, value) => events.get('input')({ target: { dataset: { path }, value, type: 'text' } });
    await click({ nav: 'users' }); assert.match(node('#content').innerHTML, /accounts-table/);
    await click({ action: 'add-account' }); input('draft.name', 'service1');
    await click({ action: 'close-dialog' }); assert.doesNotMatch(node('#content').innerHTML, /<strong>service1/);
    await click({ action: 'add-account' }); input('draft.name', 'service1'); await click({ action: 'save-account' });
    assert.match(node('#content').innerHTML, /<strong>service1/);
    await click({ nav: 'services' }); await click({ action: 'add-service' });
    assert.match(node('#content').innerHTML, /value="service1" selected/);
    await click({ nav: 'users' }); await click({ editKind: 'serviceAccounts', index: '0' }); input('draft.name', 'sensor'); await click({ action: 'save-account' });
    await click({ nav: 'services' }); assert.match(node('#content').innerHTML, /value="sensor" selected/);
    await click({ nav: 'users' }); await click({ deleteKind: 'serviceAccounts', index: '0' });
    assert.match(node('#toast').textContent, /Reassign or remove/);
    await click({ nav: 'services' }); await click({ removeService: '0' });
    await click({ nav: 'users' }); await click({ deleteKind: 'serviceAccounts', index: '0' });
    assert.match(node('#dialog-body').innerHTML, /Delete sensor/);
    await click({ action: 'close-dialog' }); assert.match(node('#content').innerHTML, /<strong>sensor/);
    await click({ deleteKind: 'serviceAccounts', index: '0' }); await click({ action: 'confirm-delete' });
    assert.doesNotMatch(node('#content').innerHTML, /<strong>sensor/);
    await click({ action: 'build-info' }); assert.match(node('#dialog-body').innerHTML, /Release/); assert.match(node('#dialog-body').innerHTML, /exact release artifact/);
    await click({ action: 'close-dialog' });
    await click({ editKind: 'root', index: '0' }); assert.match(node('#dialog-body').innerHTML, /Root SSH public keys/);
    input('draft.rootKeys', 'not a public key'); await click({ action: 'save-account' });
    assert.match(node('#account-errors').innerHTML, /Root SSH keys must/);
    await click({ action: 'close-dialog' });
    await click({ nav: 'storage' });
    assert.match(node('#content').innerHTML, /Image strategy/);
    input('updates.strategy', 'ab');
    await click({ nav: 'storage' });
    assert.match(node('#content').innerHTML, /BOOTCONFIG/);
    assert.match(node('#content').innerHTML, /Field-update storage/);
    assert.doesNotMatch(node('#content').innerHTML, /data-action="add-partition"/);
    const table = node('#content').innerHTML;
    const names = ['bootconfig','boot_a','boot_b','system_a','system_b','persistent'];
    assert.ok(names.every((name,i) => !i || table.indexOf('<strong>' + names[i-1]) < table.indexOf('<strong>' + name)));
    assert.match(table, /Fixed by Pi/); assert.match(table, /erofs/);
    await click({ editPartition: 'boot' }); input('partition.size','768M');
    await click({ action: 'close-dialog' }); assert.doesNotMatch(node('#content').innerHTML, /768M/);
    await click({ editPartition: 'boot' }); input('partition.size','768M'); await click({ action: 'save-partition' });
    assert.equal((node('#content').innerHTML.match(/<td>768M<\/td>/g) || []).length, 2);
    await click({ editPartition: 'system' }); input('partition.size','bad'); await click({ action: 'save-partition' });
    assert.match(node('#partition-errors').innerHTML, /absolute sizes/);
    await click({ action: 'close-dialog' });
    events.get('input')({ target: { dataset: { path: 'sizing.fillData' }, type: 'checkbox', checked: true } });
    await click({ nav: 'storage' });
    assert.match(node('#content').innerHTML, /Calculated data partition/);
    // A long-running server may return schema-1 projects without newly added sections.
    const { defaults } = await import('../public/model.js');
    const legacy = defaults(); legacy.project.name = 'simple-pi'; delete legacy.updates; delete legacy.sizing;
    globalThis.fetch = async () => ({ ok: true, json: async () => ({ id: 'legacy-project', config: legacy, revision: 5 }) });
    globalThis.confirm = () => true;
    await click({ open: 'legacy-project' });
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(node('#project-title').textContent, 'simple-pi');
    assert.match(node('#content').innerHTML, /Image strategy/);
    await click({ nav: 'overview' });
    assert.match(node('#content').innerHTML, /value="simple-pi"/);
    await click({ nav: 'storage' });
    await click({ action: 'add-partition' }); input('partition.label','DATA'); input('partition.mount','/data/app'); await click({ action: 'save-partition' });
    assert.match(node('#content').innerHTML, /<strong>data0/);
    await click({ deletePartition: '0' }); await click({ action: 'close-dialog' });
    assert.match(node('#content').innerHTML, /<strong>data0/);
    await click({ deletePartition: '0' }); await click({ action: 'confirm-partition-delete' });
    assert.doesNotMatch(node('#content').innerHTML, /<strong>data0/);
  } finally { timers.forEach(clearTimeout); globalThis.setTimeout = originalTimeout; globalThis.fetch = originalFetch; delete globalThis.confirm; delete globalThis.document; delete globalThis.window; delete globalThis.localStorage; }
});

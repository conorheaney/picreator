export function tar(files, prefix) {
  const chunks = [];
  for (const [path, file] of Object.entries(files)) {
    const name = `${prefix}/${path}`;
    const header = Buffer.alloc(512), body = Buffer.from(file.content);
    if (Buffer.byteLength(name) > 100) {
      const split = name.lastIndexOf('/'), prefixPart = name.slice(0, split), leaf = name.slice(split + 1);
      if (Buffer.byteLength(prefixPart) > 155 || Buffer.byteLength(leaf) > 100) throw new Error('Archive path is too long.');
      header.write(leaf, 0, 100); header.write(prefixPart, 345, 155);
    } else header.write(name, 0, 100);
    const oct = (value, offset, length) => header.write(value.toString(8).padStart(length - 1, '0') + '\0', offset, length);
    oct(file.mode, 100, 8); oct(0, 108, 8); oct(0, 116, 8); oct(body.length, 124, 12); oct(0, 136, 12);
    header.fill(32, 148, 156); header.write('0', 156); header.write('ustar\0', 257); header.write('00', 263);
    const sum = header.reduce((a, b) => a + b, 0);
    header.write(sum.toString(8).padStart(6, '0') + '\0 ', 148, 8);
    chunks.push(header, body, Buffer.alloc((512 - body.length % 512) % 512));
  }
  return Buffer.concat([...chunks, Buffer.alloc(1024)]);
}

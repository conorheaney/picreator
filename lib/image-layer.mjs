// Native rpi-image-gen extension layer. The editor writes all layout assets;
// the normal preimage hook only resolves build-time paths and filesystem IDs.
export function imageLayer(p) {
  const prefix = p.project.slug;
  const root = p.storage.rootFs, gpt = p.storage.table === 'gpt';
  const kind = gpt ? 'partition-type-uuid = L' : 'partition-type = 0x83';
  const template = `image <IMAGE_NAME>.<IMAGE_SUFFIX>.sparse { android-sparse { image = "<IMAGE_NAME>.<IMAGE_SUFFIX>" } }
image boot.vfat.sparse { android-sparse { image = "boot.vfat" } }
image root.${root}.sparse { android-sparse { image = "root.${root}" } }
image <IMAGE_NAME>.<IMAGE_SUFFIX> {
  hdimage {
    align = 8M
    partition-table-type = "${p.storage.table}"
    fill = true
    ${gpt ? '' : 'disk-signature = "<DISK_SIGNATURE>"'}
  }
  partition boot { ${gpt ? 'partition-type-uuid = U' : 'partition-type = 0xC'} image = "boot.vfat" ${gpt ? '' : 'bootable = true'} }
  partition root { ${kind} image = "root.${root}" }
${p.storage.partitions.map((d,i) => `  partition data${i} { ${kind} image = "data${i}.ext4" }`).join('\n')}
}
image boot.vfat {
  vfat { label = "BOOT" extraargs = "<VFAT_ARGS>" }
  size = <BOOT_SIZE>
  mountpoint = "/boot/firmware"
}
image root.${root} {
  ${root} { label = "ROOT" ${root === 'ext4' ? 'use-mke2fs = true\n    mke2fs-conf = "<MKE2FS_CONF>"' : ''} extraargs = "<ROOT_ARGS>" }
  size = <ROOT_SIZE>
  mountpoint = "/"
  exec-pre = "<SETUP> ROOT"
}
${p.storage.partitions.map((d,i) => `image data${i}.ext4 {
  ext4 { label = "${d.label}" use-mke2fs = true mke2fs-conf = "<MKE2FS_CONF>" }
  size = ${d.size}
  empty = true
}`).join('\n')}
`;
  const fstab = `/dev/disk/by-slot/system / ${root} ${root === 'ext4' ? 'rw,relatime,errors=remount-ro' : 'defaults'} 0 ${root === 'ext4' ? '1' : '0'}\n/dev/disk/by-slot/boot /boot/firmware vfat defaults,rw,noatime 0 2\n` + p.storage.partitions.map(d => `LABEL=${d.label} ${d.mount} ext4 defaults,nofail 0 2\n`).join('');
  return {
    [`layer/${prefix}-image.yaml`]: { content: `# METABEGIN\n# X-Env-Layer-Name: ${prefix}-image\n# X-Env-Layer-Desc: ${prefix} Standard image layer; layout assets in the companion .d directory\n# X-Env-Layer-Version: 1.0.0\n# X-Env-Layer-Requires: image-rpios\n# METAEND\n---\n`, mode: 0o600 },
    [`layer/${prefix}-image.d/genimage.cfg.in`]: { content: template, mode: 0o600 },
    [`layer/${prefix}-image.d/fstab`]: { content: fstab, mode: 0o600 },
    [`layer/${prefix}-image.d/mke2fs.conf`]: { content: '[defaults]\nbase_features = sparse_super,large_file,filetype,resize_inode,dir_index,ext_attr\ndefault_mntopts = acl,user_xattr\nenable_periodic_fsck = 0\nblocksize = 4096\ninode_size = 256\ninode_ratio = 16384\n[fs_types]\next4 = {\nfeatures = has_journal,extent,huge_file,flex_bg,metadata_csum,64bit,dir_nlink,extra_isize\n}\n', mode: 0o600 },
    [`layer/${prefix}-image.d/install-fstab.sh`]: { content: '#!/bin/bash\n# genimage invokes this hook before collecting the ROOT filesystem image.\n# $1 identifies the filesystem; IMAGEMOUNTPATH is the temporary mounted root.\n# Install the already-generated fstab, including project data mounts.\n# No disk partition is edited; failed installation stops image assembly.\n\n# --- Stop on errors ---\n\nset -euo pipefail\n\n# --- Install the mount table in the root image only ---\n\nif [[ "$1" == ROOT ]]; then\n  install -m 644 "$(dirname "$0")/fstab" "$IMAGEMOUNTPATH/etc/fstab"\nfi\n', mode: 0o700 },
    [`layer/${prefix}-image.d/hooks/preimage99-layout`]: { content: `#!/bin/bash
# Native rpi-image-gen preimage hook for ${prefix}.
# Input $1 is the assembled target filesystem; $2 is the image work directory.
# Runs after image-rpios has generated filesystem identities in img_uuids.
# The partition structure is already exported in genimage.cfg.in. This hook
# only resolves upstream sizes/IDs and absolute paths for the genimage provider.
# It never copies or modifies templates in the installed rpi-image-gen tree.
# Missing IDs/settings or a failed substitution stop the build immediately.

# -----------------------------------------------------------------------------
# Validate build inputs and locate the exported layout assets
# -----------------------------------------------------------------------------

set -euo pipefail
fs="\${1:?Missing filesystem}"
output="\${2:?Missing image work directory}"
assets="$(cd -- "$(dirname -- "\${BASH_SOURCE[0]}")/.." && pwd)"

# -----------------------------------------------------------------------------
# Read upstream filesystem identifiers and choose filesystem options
# -----------------------------------------------------------------------------

# Read filesystem IDs generated by the upstream image layer.
source "$output/img_uuids"
if [[ "$IGconf_image_rootfs_type" == ext4 ]]; then
  rootargs="-U $ROOT_UUID \${IGconf_fs_ext4_mkfs_args:-}"
else
  rootargs="-U $ROOT_UUID \${IGconf_fs_btrfs_mkfs_args:-}"
fi

# -----------------------------------------------------------------------------
# Write the resolved image layout for genimage
# -----------------------------------------------------------------------------

# Produce genimage.cfg in the image work directory, not in the exported sources.
sed -e "s|<IMAGE_NAME>|$IGconf_image_name|g" \\
    -e "s|<IMAGE_SUFFIX>|$IGconf_image_suffix|g" \\
    -e "s|<BOOT_SIZE>|$IGconf_image_boot_part_size|g" \\
    -e "s|<ROOT_SIZE>|$IGconf_image_root_part_size|g" \\
    -e "s|<DISK_SIGNATURE>|$IGconf_image_disksig|g" \\
    -e "s|<ROOT_ARGS>|$rootargs|g" \\
    -e "s|<VFAT_ARGS>|-S $IGconf_device_sector_size -i $BOOT_LABEL \${IGconf_fs_vfat_mkfs_args:-}|g" \\
    -e "s|<MKE2FS_CONF>|$assets/mke2fs.conf|g" \\
    -e "s|<SETUP>|'$assets/install-fstab.sh'|g" \\
    "$assets/genimage.cfg.in" > "$output/genimage.cfg"
`, mode: 0o700 }
  };
}
